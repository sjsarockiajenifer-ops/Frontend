// if condition


let number=10;
if(number>=0){
    console.log("positive number");
}

// if else
let age=20;
if(age>=18){
    console.log("eligible for vote");
}else{
    console.log("not eligible for vote");
}

// if,else if and else

let mark=75;
if(mark>=90){
    console.log("A grade");
}else if(mark>=60){
    console.log("B grade");
}else{
    console.log("C grade");
}

